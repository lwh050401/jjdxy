def name_images() -> dict[str, str]:
    """品名 → 实物图文件名。由 `.run/build_name_images.py` 维护，一张图只挂它真画着的那个品名。"""
    if not NAME_IMAGES_FILE.exists():
        return {}
    return json.loads(NAME_IMAGES_FILE.read_text(encoding="utf-8"))


def image_pool(slug: str, name: str) -> list[str]:
    """这件商品能挂哪些图：只认品名专属图，没有就返回空列表让前台显示占位卡。

    以前这里会退到「整类共用一张代表照」，于是毛巾套装挂上了空气净化器的照片、
    台球杆挂上了篮球的照片——图比价格更容易骗人，所以宁可无图，不可错图。
    """
    hit = name_images().get(name)
    return [hit] if hit and (IMAGE_DIR / hit).exists() else []


def purge() -> int:
    ids = [r["id"] for r in db.all_("SELECT id FROM products WHERE slug LIKE :p", {"p": PREFIX + "%"})]
    if not ids:
        print("没有可清理的演示商品")
        return 0
    db.run("DELETE FROM products WHERE slug LIKE :p", {"p": PREFIX + "%"})
    print(f"已删除 {len(ids)} 件演示商品（规格与图片随外键级联清理）")
    return len(ids)


def option_groups(slug: str, name: str, spec: dict) -> list:
    """服饰鞋包按品名挑规格组：鞋给鞋码、包给容量，其余用分类默认。

    新品类的规格口径写在数据模块的 `by_name` 里（同一类里锅看口径、刀具看件数），
    优先级高于 OPTION_RULES 的关键词规则：那是按子串猜的，by_name 是点名写死的。
    """
    for token, groups in (spec.get("by_name") or {}).items():
        if token in name:
            return groups
    for tokens, groups in OPTION_RULES.get(slug, []):
        if any(t in name for t in tokens):
            return groups
    return spec["options"]


def pick_combos(groups: list, n: int) -> list[dict]:
    """生成 n 个真实存在的规格组合：先变第一组，第三件起再动第二组，避免详情页出现选不到的组合。"""
    g0_name, g0_vals = groups[0]
    if len(groups) < 2:
        return [{g0_name: g0_vals[i % len(g0_vals)]} for i in range(n)]
    g1_name, g1_vals = groups[1]
    combos = []
    for i in range(n):
        if i < len(g0_vals):
            combos.append({g0_name: g0_vals[i], g1_name: g1_vals[0]})
        else:
            combos.append({g0_name: g0_vals[0], g1_name: g1_vals[(i - len(g0_vals)) % len(g1_vals)]})
    return combos


def build(cat_id: int, slug: str, spec: dict, index: int, rng: random.Random,
          *, name: str = "") -> tuple[dict, list[dict], list[dict]]:
    names = list(spec["facts"])
    # 补齐模式按品名点名生成，index 只用来拉开品牌、系列与 slug，不再决定品名
    name_index = names.index(name) if name else index % len(names)
    name = name or names[name_index]
    facts = spec["facts"][name]
    brand_index = (index // len(names)) % len(BRANDS)
    brand = BRANDS[brand_index]
    series = SERIES[(index // (len(names) * len(BRANDS))) % len(SERIES)]
    title = f"{brand} {series} {name}"

    jitter = rng.choice([0, 900, 1900])  # 分，带零头
    if band := OCCASION_PRICE.get(name):
        # 品名自带价位带时按品牌档次拉开：同一款西装不该五个牌子一个价
        lo, hi = band
        base = int(round((lo + (hi - lo) * min(0.94, brand_index / len(BRANDS) + rng.random() * 0.18)) * 100)) + jitter
    else:
        lo, hi = spec["price"]  # 单位：元
        step = (name_index + 1) / len(names)
        base = int(round(lo * (hi / lo) ** step) * 100) + jitter
    now = dt.datetime(2026, 1, 1) + dt.timedelta(minutes=index * 7)
    outfit = dict(OUTFIT.get(name) or {})
    if outfit.get("适用场合"):
        scene_line = "、".join(outfit["适用场合"][:3])
    else:
        scene_line = "、".join(rng.sample(spec["scenes"], k=min(2, len(spec["scenes"]))))
    description = (
        f"{title}：{facts[0]}，{facts[1]}。{facts[2]}。适用场景：{scene_line}。"
        "价格与库存按规格区分，下单后 30 分钟内未支付会自动释放。"
    )
    product = {
        "slug": f"{PREFIX}{slug}-{index + 1:04d}",
        "title": title,
        "subtitle": f"{name} · {facts[0]}",
        "brand": brand,
        "description": description,
        "category_id": cat_id,
        "price_cents": base,
        "compare_at_cents": int(base * 1.15) if index % 3 == 0 else None,
        "currency": "CNY",
        "status": "active",
        "tags": json.dumps([name] + spec["tags"][:2], ensure_ascii=False),
        "attributes": json.dumps(
            {"亮点": facts, "品类": name, "品牌系列": f"{brand} {series}", "适用场景": scene_line, **outfit},
            ensure_ascii=False,
        ),
        "rating_avg": round(rng.uniform(3.4, 4.9), 2),
        "rating_count": rng.randint(0, 80),
        "sold_count": rng.randint(0, 600),
        "featured": 0,
        "published_at": now,
        "created_at": now,
        "updated_at": now,
    }

    variants = []
    groups = option_groups(slug, name, spec)
    for v, options in enumerate(pick_combos(groups, 1 + index % 3)):
        price = base + v * max(1000, base // 10)
        variants.append({
            "sku": f"SD-{sku_code(slug)}-{index + 1:04d}-{v + 1}",
            "title": " / ".join(options.values()),
            "options": json.dumps(options, ensure_ascii=False),
            "price_cents": price,
            "compare_at_cents": int(price * 1.15) if product["compare_at_cents"] else None,
            "stock_qty": 20 + (index * 7 + v * 13) % 260,
            "reserved_qty": 0,
            "weight_gram": rng.randint(120, 4800),
            "status": "active",
            "image_url": None,
            "created_at": now,
            "updated_at": now,
        })
    product["price_cents"] = min(v["price_cents"] for v in variants)

    pool = image_pool(slug, name)
    images = [
        {"url": f"/img/products/{pool[i % len(pool)]}", "alt": title, "sort": i}
        for i in range(1 + (index % len(pool)))
    ] if pool else []
    for i, v in enumerate(variants):
        v["image_url"] = images[i]["url"] if i < len(images) else (images[0]["url"] if images else None)
    return product, variants, images


