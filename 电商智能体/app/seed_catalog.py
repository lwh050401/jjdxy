# 新品类词表按模块放在 app/seed_data/ 下（一个模块管几类商品），在这里合并进来：
# 主文件只留生成逻辑，补品类只加数据文件，也免得几千人改同一处撞车。
CATEGORY_META: dict[str, dict] = dict(seed_data.CATEGORY_META)


def merge_seed_data() -> None:
    if seed_data.LOAD_ERRORS:
        broken = "；".join(f"{k}: {v}" for k, v in sorted(seed_data.LOAD_ERRORS.items()))
        raise SystemExit(f"品类数据包读不进去，先修好再灌数据 → {broken}")
    # 品名要全站唯一：它既是 attributes 里的「品类」，也是 --fill 认缺口和穿搭词表对号的键，
    # 同一个品名挂在两个分类下，补货会只补一边、推荐会拿到两份同源的商品。
    taken = {name: slug for slug, spec in CATALOG.items() for name in spec["facts"]}
    for slug, spec in seed_data.CATALOG_EXTRA.items():
        if slug in CATALOG:
            raise SystemExit(f"新品类「{slug}」顶掉了站内已有分类，改 slug 再来")
        for name in spec["facts"]:
            if name in taken:
                raise SystemExit(f"品名「{name}」已挂在分类「{taken[name]}」，新品类「{slug}」不能再用")
            taken[name] = slug
        CATALOG[slug] = spec
    for slug, names in seed_data.NAMES_EXTRA.items():
        if slug not in CATALOG:
            raise SystemExit(f"NAMES_EXTRA 指向不存在的分类「{slug}」")
        for name, facts in names.items():
            if name in taken:
                raise SystemExit(f"品名「{name}」站内已有（分类「{taken[name]}」），别再往「{slug}」补一份")
            taken[name] = slug
            CATALOG[slug]["facts"][name] = facts
    # 追加排在已有规则之后：新补的「登山鞋」拿到鞋码，老的「板鞋」仍走原来那条
    for slug, rules in seed_data.OPTION_RULES_EXTRA.items():
        OPTION_RULES.setdefault(slug, []).extend(rules)


