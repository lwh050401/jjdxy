def expand(query: str) -> list[str]:
    """返回要一起检索的若干说法，第一条永远是用户原话。"""
    text = (query or "").strip()
    if not text:
        return []
    out = [text]
    for spoken, catalog_word in SYNONYMS.items():
        if spoken in text and spoken != catalog_word:
            out.append(text.replace(spoken, catalog_word))
    return list(dict.fromkeys(out))


# 用户说的组合词，货不一定照这个顺序写：站内标题是「Terra Air 折叠露营桌」，
# 搜「折叠桌」按连续串比就差中间那个「露营」。同义词表补不动这一类（右半边得真是站内用词，
# 「折叠桌」也不是站内某个品类名），所以给一条通用规则：允许用户词的字中间插字。
# 只拆纯汉字、至少三个字：「雨伞」不拆（拆成「雨」+「伞」会把雨具和伞具乱并），
# 「typec」「4g」这类带字母数字的也不拆，截出来的半截词没有意义。
GAP_MIN_LEN = 3
CJK = re.compile(r"[一-鿿]+")


def gap_pattern(needle: str) -> str:
    """把「折叠桌」变成 `%折%叠%桌%`：字序不变，中间允许插别的字。不满足条件返回空串。"""
    text = (needle or "").strip()
    if len(text) < GAP_MIN_LEN or not CJK.fullmatch(text):
        return ""
    return "%" + "%".join(text) + "%"
