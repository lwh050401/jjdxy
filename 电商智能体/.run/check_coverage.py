def word_list() -> list[str]:
    seen: list[str] = []
    for words in WORDS.values():
        for w in words:
            if w not in seen:
                seen.append(w)
    return seen


def flat(text: str) -> str:
    return re.sub(r"\s+", "", text).lower()


def gap_hit(needle: str, joined: str) -> bool:
    """字序不变、中间允许插字：与 `synonyms.gap_pattern()` 同一条规则，只在三个字以上的纯汉字上生效。"""
    word = flat(needle)
    if len(word) < 3 or not re.fullmatch(r"[一-鿿]+", word):
        return False
    it = iter(joined)
    return all(ch in it for ch in word)


def title_covers(title: str, word: str) -> bool:
    """标题里是否真的同时住下这几个词（同义词与插字说法也算，用户搜「充电宝」就是搜「移动电源」，
    说「折叠桌」时站内那件叫「折叠露营桌」）。"""
    joined = flat(title)
    return all(
        any(flat(n) in joined or gap_hit(n, joined) for n in catalog.needles(tok)) for tok in word.split()
    )


def hit_count(word: str) -> int:
    if " " not in word:
        return catalog.search(q=word, per_page=1)["total"]
    return sum(
        1 for x in catalog.search(q=word, per_page=20)["items"] if title_covers(x["title"], word)
    )


def main() -> int:
    words = word_list()
    print(f"核对 {len(words)} 个购物词，覆盖 {len(WORDS)} 个场景……\n")
    misses: dict[str, list[str]] = {}
    thin: dict[str, list[str]] = {}
    done: set[str] = set()
    gaps: dict[str, str] = {}
    for group, group_words in WORDS.items():
        for w in group_words:
            if w in done:
                continue
            done.add(w)
            total = hit_count(w)
            if total == 0:
                misses.setdefault(group, []).append(w)
                gaps[w] = group
            elif total < 3:
                thin.setdefault(group, []).append(f"{w}({total})")
    if "--dump-gaps" in sys.argv:
        path = Path(__file__).resolve().parents[1] / ".run/gaps.json"
        path.write_text(json.dumps(gaps, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"缺口词已写给施工图：{path}（{len(gaps)} 个）")
    hit = len(words) - sum(len(v) for v in misses.values())
    print(f"有货 {hit}/{len(words)}，缺口 {len(words) - hit} 个\n")
    for group in misses:
        print(f"  [{group}] 0 命中：{'、'.join(misses[group])}")
    if thin:
        print("\n  少于 3 件（挑得太薄，用户点进去就没了）：")
        for group, items in thin.items():
            print(f"  [{group}] {'、'.join(items)}")
    if misses:
        print(f"\n结论：还有 {len(words) - hit} 个词查不到货，先补品类再谈验收。")
        return 1
    print("\n结论：全部购物词都有真实现货。")
    return 0


